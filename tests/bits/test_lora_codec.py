def _codec() -> CodecSpec:
    return CodecSpec(
        name="css_explicit",
        path=[
            CodecStep(conv="nibble_swap", params={}),
            # frame_body_len=2056: 255 whitened payload bytes (2040 bits)
            # + 2 unwhitened CRC bytes (16 bits) = 257 bytes = 2056 bits.
            CodecStep(conv="segment", params={"frame_body_len": 2056}),
            CodecStep(conv="fixed_frame", params={"payload_bits": 2056}),
            # _WHITEN covers payload bytes 0..254; the trailing "0000" leaves
            # the 2-byte CRC field (bytes 255..256) unmodified after descramble.
            CodecStep(conv="descramble", params={"sequence": _WHITEN}),
            CodecStep(
                conv="crc",
                params={
                    "poly": 0x1021,
                    "bits": 16,
                    "init": 0,
                    "fold_tail": 2,
                    "checksum_le": True,
                },
            ),
            # After crc strips the 2-byte CRC field, the payload is 255 bytes
            # (2040 bits) of de-whitened LoRa data.
            CodecStep(
                conv="parse",
                params={
                    "bit_order": "msb",
                    "fields": [{"name": "payload", "bits": 2040}],
                },
            ),
        ],
    )


def test_lora_codec_decodes_golden_bits_crc_valid() -> None:
    prog = compile_codec(_codec(), registry(), "rx")
    carrier = RxCarrier(bits=np.array(_GOLDEN_BITS, dtype=np.uint8))
    out = run_program(prog, carrier)
    assert out.frames, "no frame produced"
    f = out.frames[0]
    assert f.crc_ok is True
    assert f.payload.startswith(b"RF fingerpring Project for Lora")
